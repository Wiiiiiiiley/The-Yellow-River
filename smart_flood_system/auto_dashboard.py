"""
Auto-Dashboard - Automated Reporting & Monitoring
=================================================

Automated evolution reporting and Streamlit dashboard integration.

Features:
1. Auto-generate evolution_report.md
2. Track generation history
3. Display on Streamlit dashboard
4. Physics personality trends
"""

import os
import json
import logging
from pathlib import Path
from datetime import datetime, timedelta
from typing import Dict, List

import matplotlib.pyplot as plt
from matplotlib import rcParams

rcParams['font.sans-serif'] = ['SimHei', 'Arial Unicode MS', 'DejaVu Sans']
rcParams['axes.unicode_minus'] = False

logger = logging.getLogger(__name__)


class AutoDashboard:
    """
    Automated dashboard and reporting system.
    
    Generates:
    - evolution_report.md after each evolution
    - Daily system status reports
    - Trend visualizations
    """
    
    def __init__(
        self,
        report_interval: int = 24,
        port: int = 8501,
        report_dir: str = "reports/evolution/"
    ):
        self.report_interval = report_interval
        self.port = port
        self.report_dir = Path(report_dir)
        self.report_dir.mkdir(parents=True, exist_ok=True)
        
        # History tracking
        self.history_file = self.report_dir / "evolution_history.json"
        self.history = self._load_history()
        
        logger.info(f"AutoDashboard initialized (port={port})")
    
    def _load_history(self) -> List[Dict]:
        """Load evolution history."""
        if self.history_file.exists():
            with open(self.history_file, 'r') as f:
                return json.load(f)
        return []
    
    def generate_evolution_report(self, evolution_result: Dict):
        """
        Generate markdown report after evolution.
        
        Creates evolution_report.md with:
        - Generation info
        - Physics residual trends
        - Model promotion status
        - Learning statistics
        """
        timestamp = datetime.now()
        report_name = f"evolution_report_{timestamp:%Y%m%d_%H%M%S}.md"
        report_path = self.report_dir / report_name
        
        # Add to history
        self.history.append(evolution_result)
        self._save_history()
        
        # Generate report content
        content = self._build_report_content(evolution_result)
        
        # Save markdown
        with open(report_path, 'w') as f:
            f.write(content)
        
        # Also update latest symlink
        latest_path = self.report_dir / "evolution_report_latest.md"
        if latest_path.exists():
            latest_path.unlink()
        
        try:
            latest_path.symlink_to(report_path.name)
        except:
            # If symlink fails, just copy
            import shutil
            shutil.copy(report_path, latest_path)
        
        logger.info(f"✓ Evolution report generated: {report_path}")
        
        # Generate visualization
        self._generate_trend_plot()
        
        return str(report_path)
    
    def _build_report_content(self, result: Dict) -> str:
        """Build markdown report content."""
        
        # Calculate trends
        if len(self.history) > 1:
            prev_residual = self.history[-2].get('physics_residual', 0)
            residual_change = result['physics_residual'] - prev_residual
        else:
            residual_change = 0
        
        # Generation progress
        gen = result['generation']
        
        content = f"""# Evolution Report {datetime.now():%Y-%m-%d %H:%M:%S}

## Model Evolution Summary

| Metric | Value |
|--------|-------|
| **Generation** | {gen} |
| **Status** | {'🎉 PROMOTED' if result['promoted'] else '⏭️ Kept Previous'} |
| **Physics Residual** | {result['physics_residual']:.6f} |
| **Validation Loss** | {result['val_loss']:.6f} |
| **Improvement** | {result['improvement_ratio']*100:.1f}% |

## Physics Personality Trends

```
Generation: {'█' * gen}{'░' * (20-gen)} {gen}/20
Physics Residual: {result['physics_residual']:.4f} {'↓' if residual_change < 0 else '↑'}
```

## Learning Statistics

- **Data Accumulated**: See daily report
- **Training Epochs**: 100 (fine-tuning)
- **Historical Buffer**: 20% retention
- **Auto-HP Triggered**: {'Yes ⚠️' if result['auto_hp_triggered'] else 'No ✓'}

## Model Lineage

"""
        
        # Add generation lineage
        for i, h in enumerate(self.history[-5:], 1):
            status = "✓" if h.get('promoted') else "○"
            content += f"{status} Gen-{h['generation']}: residual={h['physics_residual']:.4f}\n"
        
        content += f"""
## Physical Parameters (Current)

| Parameter | Value | Status |
|-----------|-------|--------|
| n (Manning) | 0.030 | ✓ Calibrated |
| S₀ (Bed Slope) | 0.001 | ✓ Calibrated |
| B (Channel Width) | 50.0 m | ✓ Calibrated |
| Porosity | 0.40 | ✓ Exner |

## Next Evolution Trigger

- Accumulate {7} days of new data
- Current progress: See system status

---
*Auto-generated by AutoPilot v1.0*
"""
        
        return content
    
    def generate_daily_report(self, system_status: Dict) -> str:
        """Generate daily system status report."""
        timestamp = datetime.now()
        report_path = self.report_dir / f"daily_report_{timestamp:%Y%m%d}.md"
        
        content = f"""# Daily System Status Report

**Date**: {timestamp:%Y-%m-%d %H:%M:%S}  
**Generation**: {system_status.get('current_model_generation', 'N/A')}  
**Status**: {'✓ Healthy' if system_status.get('is_healthy') else '⚠ Issues Detected'}

## Operational Metrics

| Metric | Value |
|--------|-------|
| Last Download | {system_status.get('last_download', 'Never')} |
| Last Training | {system_status.get('last_training', 'Never')} |
| Last Evolution | {system_status.get('last_evolution', 'Never')} |
| Accumulated Data | {system_status.get('accumulated_data_days', 0)} days |
| Physics Residual | {system_status.get('physics_residual', 'N/A')} |
| Active Jobs | {', '.join(system_status.get('active_jobs', []))} |

## Evolution Progress

```
Model Generation: {system_status.get('current_model_generation', 1)}
Data Queue: {system_status.get('accumulated_data_days', 0)}/7 days
```

## 24h Activity Log

- See detailed logs in `logs/auto_pilot_*.log`

---
*Auto-generated by AutoPilot v1.0*
"""
        
        with open(report_path, 'w') as f:
            f.write(content)
        
        return str(report_path)
    
    def _save_history(self):
        """Save evolution history."""
        with open(self.history_file, 'w') as f:
            json.dump(self.history, f, indent=2)
    
    def _generate_trend_plot(self):
        """Generate evolution trend visualization."""
        if len(self.history) < 2:
            return
        
        fig, axes = plt.subplots(1, 2, figsize=(12, 5))
        fig.suptitle('Model Evolution Trends', fontsize=14, fontweight='bold')
        
        generations = [h['generation'] for h in self.history]
        residuals = [h['physics_residual'] for h in self.history]
        val_losses = [h['val_loss'] for h in self.history]
        
        # Plot 1: Physics residual over generations
        ax = axes[0]
        ax.plot(generations, residuals, 'b-o', linewidth=2, markersize=8)
        ax.axhline(y=0.1, color='r', linestyle='--', label='Target Threshold')
        ax.set_xlabel('Generation')
        ax.set_ylabel('Physics Residual')
        ax.set_title('Physics Residual Trend')
        ax.legend()
        ax.grid(True, alpha=0.3)
        
        # Plot 2: Validation loss
        ax = axes[1]
        ax.plot(generations, val_losses, 'g-s', linewidth=2, markersize=8)
        ax.set_xlabel('Generation')
        ax.set_ylabel('Validation Loss')
        ax.set_title('Learning Progress')
        ax.grid(True, alpha=0.3)
        
        plt.tight_layout()
        
        plot_path = self.report_dir / "evolution_trends.png"
        plt.savefig(plot_path, dpi=150, bbox_inches='tight')
        plt.close()
        
        logger.info(f"✓ Trend plot saved: {plot_path}")
    
